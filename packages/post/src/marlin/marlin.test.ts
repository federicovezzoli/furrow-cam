import type { Toolpath } from "@furrow/cam-core";
import type { Operation, Stock, Tool } from "@furrow/document";
import { drill, endMill, machine } from "@furrow/document/fixtures";
import { describe, expect, it } from "vitest";
import type { PostInput } from "../post";
import { marlin } from "./marlin";

const stock: Stock = {
  width: 300,
  height: 200,
  thickness: 18,
  xyOrigin: { anchor: "bottom_left" },
  zOrigin: "stock_top",
  touchOff: null,
  twoSided: null,
  tabs: null,
};

function operation(name: string, tool: Tool): Operation {
  return {
    id: "0d9c8b7a-6f5e-4d3c-ab1a-0f9e8d7c6b5a",
    type: "drill",
    name,
    enabled: true,
    stockSide: "top",
    targets: [],
    tool,
    params: { depth: 5, peck: false, stepOver: 40, pins: false, points: [] },
  };
}

const plunge: Toolpath = {
  moves: [
    { kind: "rapid", to: [100, 50, 5] },
    { kind: "feed", to: [100, 50, -5], feedRate: 500 },
    { kind: "rapid", to: [100, 50, 5] },
    { kind: "rapid", to: [120, 50, 5] },
    { kind: "feed", to: [120, 50, -5], feedRate: 500 },
    { kind: "rapid", to: [120, 50, 5] },
  ],
  warnings: [],
};

function post(input: Partial<PostInput> = {}) {
  return marlin.post({
    name: "Test",
    stock,
    machine: { ...machine, postProcessor: "marlin" },
    safeZ: 5,
    operations: [
      { operation: operation("Holes", drill), toolpath: plunge },
      { operation: operation("Slots", endMill), toolpath: plunge },
    ],
    ...input,
  }).gcode;
}

describe("marlin", () => {
  it("writes one command a line, ; comments and no M30", () => {
    const lines = post().split("\n");
    expect(lines.slice(0, 2)).toEqual(["; Test", "; Generated by Furrow CAM"]);
    expect(lines).toContain("G21");
    expect(lines).toContain("G90");
    expect(lines.some((line) => line.startsWith("("))).toBe(false);
    expect(post()).not.toMatch(/G94|G17|M30|M84/);
    expect(lines.slice(-4)).toEqual(["G0 Z5 F10000", "M5", "G0 X0 Y0", ""]);
  });

  it("dwells in seconds after starting the spindle", () => {
    expect(post()).toContain("M3 S12000\nG4 S5\n");
  });

  it("gives rapids the machine's XY feed, and the next cut its own", () => {
    expect(post()).toContain("G1 Z-5 F500\nG0 Z5 F10000\nG0 X120\nG1 Z-5 F500\nG0 Z5 F10000\n");
  });

  it("pauses with its message on the LCD at a tool change", () => {
    expect(post()).toContain(
      'M5\nG0 Z5 F10000\nM0 Change the bit to 1/4" 2-flute upcut, 6.35 mm and zero Z again\nG21\nG90\n',
    );
  });

  it("pauses the same way at the touch-off pad's default tool change", () => {
    const padded = { ...stock, touchOff: { x: 3, y: 3, diameter: 6, toolChange: null } };
    expect(post({ stock: padded })).toContain(
      "M0 Change the bit and zero Z on the touch-off pad\n",
    );
  });
});
