import type { Toolpath, Vec3 } from "@furrow/cam-core";
import type { Machine, Operation, Stock, StockAnchor, Tool } from "@furrow/document";
import { drill as drillBit, endMill, lowRider, machine } from "@furrow/document/fixtures";
import { describe, expect, it } from "vitest";
import { formatNumber, grbl } from "./grbl";
import type { PostInput } from "./post";

const stock: Stock = {
  width: 300,
  height: 200,
  thickness: 18,
  xyOrigin: { anchor: "bottom_left" },
  zOrigin: "stock_top",
};

function operation(name: string, tool: Tool = endMill): Operation {
  return {
    id: "0d9c8b7a-6f5e-4d3c-ab1a-0f9e8d7c6b5a",
    type: "drill",
    name,
    enabled: true,
    shapeIds: [],
    tool,
    params: { depth: 5, peck: false },
  };
}

/** A plunge at `at` (stock coordinates) down to 5 mm below the stock top. */
function plunge(at: [number, number]): Toolpath {
  return {
    moves: [
      { kind: "rapid", to: [...at, 5] },
      { kind: "feed", to: [...at, -5], feedRate: 500 },
      { kind: "rapid", to: [...at, 5] },
    ],
    warnings: [],
  };
}

function post(input: Partial<PostInput>) {
  return grbl.post({
    name: "Test",
    stock,
    machine: null,
    safeZ: 5,
    operations: [{ operation: operation("Holes"), toolpath: plunge([100, 50]) }],
    ...input,
  });
}

/** The program's motion lines, without the header and footer. */
function motion(gcode: string): string[] {
  return gcode.split("\n").filter((line) => /^G[01] /.test(line));
}

describe("grbl", () => {
  it("writes a complete program", () => {
    expect(post({}).gcode).toBe(
      [
        "(Test)",
        "(Generated by Furrow CAM)",
        "(Zero: X Y at the bottom-left corner of the stock, Z at the stock top)",
        "G21 G90 G94 G17",
        '(Tool: 1/4" 2-flute upcut, 6.35 mm)',
        "(Operation: Holes)",
        "G0 Z5",
        "M3 S18000",
        "G0 X100 Y50",
        "G1 Z-5 F500",
        "G0 Z5",
        "M5",
        "G0 X0 Y0",
        "M30",
        "",
      ].join("\n"),
    );
  });

  describe("work coordinates (ADR-0014, PRD-0002 Z8)", () => {
    const anchors: [StockAnchor, Vec3][] = [
      ["bottom_left", [100, 50, 0]],
      ["bottom_center", [-50, 50, 0]],
      ["bottom_right", [-200, 50, 0]],
      ["middle_left", [100, -50, 0]],
      ["center", [-50, -50, 0]],
      ["middle_right", [-200, -50, 0]],
      ["top_left", [100, -150, 0]],
      ["top_center", [-50, -150, 0]],
      ["top_right", [-200, -150, 0]],
    ];

    it.each(anchors)("measures from the %s anchor", (anchor, [x, y]) => {
      const { gcode } = post({ stock: { ...stock, xyOrigin: { anchor } } });
      expect(motion(gcode)).toEqual([
        "G0 Z5",
        `G0 X${x} Y${y}`,
        "G1 Z-5 F500",
        "G0 Z5",
        "G0 X0 Y0",
      ]);
    });

    it("measures from a custom zero, also outside the stock", () => {
      const inside = post({ stock: { ...stock, xyOrigin: { anchor: "custom", x: 40, y: 25.5 } } });
      expect(motion(inside.gcode)[1]).toBe("G0 X60 Y24.5");
      const outside = post({ stock: { ...stock, xyOrigin: { anchor: "custom", x: -10, y: 210 } } });
      expect(motion(outside.gcode)[1]).toBe("G0 X110 Y-160");
    });

    it("measures Z from the machine bed", () => {
      const { gcode } = post({ stock: { ...stock, zOrigin: "machine_bed" } });
      expect(motion(gcode)).toEqual(["G0 Z23", "G0 X100 Y50", "G1 Z13 F500", "G0 Z23", "G0 X0 Y0"]);
    });

    it("names the zero in the header", () => {
      const { gcode } = post({
        stock: { ...stock, xyOrigin: { anchor: "custom", x: 12, y: -3 }, zOrigin: "machine_bed" },
      });
      expect(gcode).toContain(
        "(Zero: X Y at X12 Y-3 mm from the stock's bottom-left corner, Z at the machine bed)",
      );
    });
  });

  it("writes only the words that change", () => {
    const toolpath: Toolpath = {
      moves: [
        { kind: "rapid", to: [0, 0, 5] },
        { kind: "feed", to: [0, 0, -2], feedRate: 500 },
        { kind: "feed", to: [10, 0, -2], feedRate: 1500 },
        { kind: "feed", to: [10, 10, -2], feedRate: 1500 },
        // Rounds to where the tool already is.
        { kind: "feed", to: [10, 10.0001, -2], feedRate: 1500 },
        { kind: "rapid", to: [10, 10, 5] },
      ],
      warnings: [],
    };
    const { gcode } = post({ operations: [{ operation: operation("Square"), toolpath }] });
    expect(motion(gcode)).toEqual([
      "G0 Z5",
      "G0 X0 Y0",
      "G1 Z-2 F500",
      "G1 X10 F1500",
      "G1 Y10",
      "G0 Z5",
      "G0 X0 Y0",
    ]);
  });

  describe("spindle", () => {
    it("omits S for a manual spindle", () => {
      const { gcode } = post({ machine: { ...lowRider, toolChange: null } });
      expect(gcode).toContain("\nM3\n");
    });

    it("keeps the speed in the machine's range and warns", () => {
      const fast = { ...endMill, spindleRpm: 40000 };
      const { gcode, warnings } = post({
        machine,
        operations: [{ operation: operation("Holes", fast), toolpath: plunge([0, 0]) }],
      });
      expect(gcode).toContain("M3 S30000");
      expect(warnings).toEqual([
        "Holes: the tool's 40000 RPM is outside the machine's spindle range, so 30000 RPM is used.",
      ]);
    });
  });

  describe("feeds", () => {
    const slow: Machine = { ...machine, maxFeedXY: 1000, maxFeedZ: 300 };

    it("slows moves to the machine's maximum per axis and warns", () => {
      const toolpath: Toolpath = {
        moves: [
          { kind: "rapid", to: [0, 0, 5] },
          // Plunge: Z only, limited to 300.
          { kind: "feed", to: [0, 0, 0], feedRate: 500 },
          // Ramp 30 mm across, 4 mm down: XY needs 1500 × 30 / √916 ≈ 1486 > 1000,
          // so the feed is 1000 × √916 / 30 ≈ 1008.849; Z is then ≈ 133.3, within 300.
          { kind: "feed", to: [30, 0, -4], feedRate: 1500 },
          // XY only, within the limit.
          { kind: "feed", to: [30, 10, -4], feedRate: 900 },
        ],
        warnings: [],
      };
      const { gcode, warnings } = post({
        machine: slow,
        operations: [{ operation: operation("Ramp"), toolpath }],
      });
      expect(motion(gcode).slice(2, 5)).toEqual([
        "G1 Z0 F300",
        "G1 X30 Z-4 F1008.849",
        "G1 Y10 F900",
      ]);
      expect(warnings).toEqual(["Ramp: 2 moves slowed to the machine's maximum feed."]);
    });

    it("leaves feeds alone without a machine profile", () => {
      expect(post({}).warnings).toEqual([]);
    });
  });

  describe("tool changes", () => {
    const drill: Tool = { ...drillBit, diameter: 6.35 };
    const operations = [
      { operation: operation("Profile"), toolpath: plunge([0, 0]) },
      // Same bit, other feeds: no change.
      {
        operation: operation("Pocket", { ...endMill, feedRate: 900, color: "#ff0000" }),
        toolpath: plunge([10, 0]),
      },
      { operation: operation("Holes", drill), toolpath: plunge([20, 0]) },
    ];

    it("pauses only when the bit changes", () => {
      const { gcode } = post({ operations });
      expect(gcode.match(/^M0/gm)).toHaveLength(1);
      expect(gcode).toContain(
        [
          "(Tool: 6 mm drill, 6.35 mm)",
          "M5",
          "G0 Z5",
          "M0 (Change the bit to 6 mm drill, 6.35 mm and zero Z again)",
          "(Operation: Holes)",
          "G0 Z5",
          "M3 S12000",
          "G0 X20 Y0",
        ].join("\n"),
      );
    });
  });

  describe("custom G-code blocks (#11)", () => {
    const custom: Machine = {
      ...machine,
      programStart: "G21\nG90\nM62 P1 (start spindle pin 27)",
      programEnd: "M63 P1\r\nM2\n",
      operationStart: "G4 P1",
      toolChange: "G0 Z20\nM0 (Switch off the router and change the bit)",
    };
    const drill: Tool = { ...endMill, name: "Drill", type: "drill", cutDirection: null };

    it("replace the defaults verbatim", () => {
      const { gcode } = post({
        machine: custom,
        operations: [
          { operation: operation("Profile"), toolpath: plunge([0, 0]) },
          { operation: operation("Holes", drill), toolpath: plunge([20, 0]) },
        ],
      });
      expect(gcode).toContain(
        "(Zero Z again after each tool change)\nG21\nG90\nM62 P1 (start spindle pin 27)\nG21 G90 G94 G17\n(Tool:",
      );
      expect(gcode).not.toContain("(Operation:");
      expect(gcode.match(/^G4 P1$/gm)).toHaveLength(2);
      // The modes and every word are written again after a custom block, which
      // may have moved the tool or switched to relative coordinates.
      expect(gcode).toContain(
        [
          "(Tool: Drill, 6.35 mm)",
          "G0 Z20",
          "M0 (Switch off the router and change the bit)",
          "G21 G90 G94 G17",
          "G4 P1",
          "G21 G90 G94 G17",
          "G0 Z5",
          "M3 S18000",
          "G0 X20 Y0",
        ].join("\n"),
      );
      expect(gcode.endsWith("G0 Z5\nM63 P1\nM2\n")).toBe(true);
      expect(gcode).not.toContain("M30");
    });
  });

  it("asks for Z to be zeroed again only when the bit changes", () => {
    expect(post({}).gcode).not.toContain("Zero Z again");
  });

  it("refuses a toolpath that starts with a feed", () => {
    const toolpath: Toolpath = {
      moves: [{ kind: "feed", to: [0, 0, -1], feedRate: 500 }],
      warnings: [],
    };
    expect(() => post({ operations: [{ operation: operation("Bad"), toolpath }] })).toThrow(
      "Bad: the toolpath starts with a feed",
    );
  });

  it("keeps parentheses and line breaks out of comments", () => {
    const { gcode } = post({ name: "Sign (v2)\nfinal" });
    expect(gcode.split("\n")[0]).toBe("(Sign [v2] final)");
  });
});

describe("formatNumber", () => {
  it("rounds to 3 decimals without trailing zeros or -0", () => {
    expect(formatNumber(100)).toBe("100");
    expect(formatNumber(1.5)).toBe("1.5");
    expect(formatNumber(1 / 3)).toBe("0.333");
    expect(formatNumber(-0.0004)).toBe("0");
    expect(formatNumber(-0)).toBe("0");
    expect(formatNumber(-12.3456)).toBe("-12.346");
  });
});
