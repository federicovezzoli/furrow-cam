import { activeTouchOff, stockOffset, type Vec3 } from "@furrow/cam-core";
import type { Machine, Stock, StockAnchor, Tool, TouchOff } from "@furrow/document";
import { formatNumber } from "./format";
import { type PostInput, type PostOutput, type PostProcessor, postSteps } from "./post";
import { fillTouchOffBlock } from "./touch-off";

/** The modes every coordinate assumes: millimetres, absolute, feed per minute, XY plane. */
const MODES = "G21 G90 G94 G17";

/**
 * GRBL 1.1 (PRD-0001 R11), in millimetres and absolute coordinates, measured
 * from the work origin (ADR-0014, ADR-0016).
 *
 * - The program starts with `MODES` and ends with the spindle off, a rapid up
 *   to the retract height, a rapid to the XY zero and `M30`.
 * - Each operation starts with a comment naming it, rises to the retract
 *   height and only then starts the spindle (`M3`, with `S` unless the
 *   machine has a manual spindle), so it never spins up touching the work.
 *   Every word is written in full: the user may have jogged during a pause.
 * - An operation with clearing moves (ADR-0026) is written as two: the
 *   clearing moves with its clearing tool, named "<operation>, clearing",
 *   then its own.
 * - The first tool is assumed loaded. When the next operation's bit differs,
 *   GRBL has no `M6`, so the tool change turns the spindle off, rises and
 *   pauses with `M0`, asking for Z to be zeroed again: there are no tool
 *   length offsets. With a touch-off pad (ADR-0041), it rapids over the
 *   pad's centre before pausing, and before a custom tool-change block. A
 *   pad's own tool change (ADR-0043) replaces all of it, its placeholders
 *   filled in.
 * - Each tool's cutter shape is written in a machine-readable comment
 *   (`toolShapeComment`, ADR-0042) when the cutter is in the spindle: for the
 *   first tool in the header, before the program-start block; at a tool
 *   change after the pause or the custom tool-change block.
 * - Feeds are lowered so neither the XY nor the Z component of a move exceeds
 *   the machine's maximum, and spindle speeds are kept in its range; either
 *   warns.
 * - The machine's custom blocks replace the program start, the program end,
 *   the operation comment and the tool change, copied verbatim. They may move
 *   the tool or change modes (a `G91` retract), so `MODES` and every word are
 *   written again after one, except at the end.
 */
export const grbl: PostProcessor = { id: "grbl", extension: ".gcode", post: postGrbl };

function postGrbl({ name, stock, machine, safeZ, operations }: PostInput): PostOutput {
  const out = new GcodeWriter(stockOffset(stock));
  const warnings: string[] = [];
  /** A custom block, then the modes the program's coordinates need. */
  function custom(block: string) {
    out.custom(block);
    out.line(MODES);
  }

  out.comment(name);
  out.comment("Generated by Furrow CAM");
  out.comment(`Zero: X Y ${xyZeroLabel(stock)}, Z ${zZeroLabel(stock)}`);
  const steps = postSteps(operations);
  const changesBit = steps.some((step, i) => {
    const before = steps[i - 1];
    return before !== undefined && !sameBit(before.tool, step.tool);
  });
  const pad = activeTouchOff(stock);
  if (changesBit) {
    out.comment(
      pad
        ? `Zero Z again on the touch-off pad after each tool change: ${padLabel(stock, pad)}`
        : "Zero Z again after each tool change",
    );
  }
  const first = steps[0];
  if (first) out.line(toolShapeComment(first.tool));
  if (machine?.programStart) custom(machine.programStart);
  else out.line(MODES);

  let tool: Tool | null = null;
  for (const step of steps) {
    if (tool === null || !sameBit(tool, step.tool)) {
      out.comment(`Tool: ${toolLabel(step.tool)}`);
      if (tool !== null) {
        out.forget();
        if (pad?.toolChange) {
          // The project's own tool change on the pad (ADR-0043) replaces it all.
          custom(fillTouchOffBlock(pad.toolChange, stock, pad));
        } else if (machine?.toolChange) {
          // Over the pad first, where Z is zeroed; the block may stop the spindle.
          if (pad) {
            out.rapid({ z: safeZ });
            out.rapid({ x: pad.x, y: pad.y });
          }
          custom(machine.toolChange);
        } else {
          out.line("M5");
          out.rapid({ z: safeZ });
          if (pad) out.rapid({ x: pad.x, y: pad.y });
          const zero = pad ? "zero Z on the touch-off pad" : "zero Z again";
          out.line(`M0 ${comment(`Change the bit to ${toolLabel(step.tool)} and ${zero}`)}`);
        }
        out.line(toolShapeComment(step.tool));
      }
    }
    tool = step.tool;

    if (machine?.operationStart) custom(machine.operationStart);
    else out.comment(`Operation: ${step.name}`);

    // Getting to the first entry point safely is the post-processor's job.
    // The user may have jogged during a pause, so nothing is taken as known.
    out.forget();
    out.rapid({ z: safeZ });

    const rpm = spindleSpeed(step.tool.spindleRpm, machine);
    if (rpm.clamped) {
      warnings.push(
        `${step.name}: the tool's ${step.tool.spindleRpm} RPM is outside the machine's ` +
          `spindle range, so ${rpm.value} RPM is used.`,
      );
    }
    out.line(rpm.value === null ? "M3" : `M3 S${rpm.value}`);

    let previous: Vec3 | null = null;
    let clamped = 0;
    for (const move of step.moves) {
      const [x, y, z] = move.to;
      if (move.kind === "rapid") out.rapid({ x, y, z });
      else {
        // The `Toolpath` contract: the first move is a rapid to the first entry point.
        if (previous === null) throw new Error(`${step.name}: the toolpath starts with a feed`);
        const feed = limitFeed(previous, move.to, move.feedRate, machine);
        if (feed < move.feedRate) clamped++;
        out.feed({ x, y, z }, feed);
      }
      previous = move.to;
    }
    if (clamped > 0) {
      warnings.push(
        `${step.name}: ${plural(clamped, "move")} slowed to the machine's maximum feed.`,
      );
    }
  }

  if (machine?.programEnd) out.custom(machine.programEnd);
  else {
    out.line("M5");
    out.rapid({ z: safeZ });
    out.rapidWork({ x: 0, y: 0 });
    out.line("M30");
  }
  return { gcode: out.toString(), warnings };
}

type Axes = { x?: number; y?: number; z?: number };
const AXES = ["x", "y", "z"] as const;

/**
 * Collects G-code lines, writing only the coordinates and feed that change.
 * Coordinates go in in stock coordinates and come out in work coordinates.
 */
class GcodeWriter {
  private readonly lines: string[] = [];
  /** Last written value of each word, as formatted, or absent when unknown. */
  private written: Partial<Record<"x" | "y" | "z" | "f", string>> = {};

  constructor(private readonly offset: Vec3) {}

  line(text: string) {
    this.lines.push(text);
  }

  comment(text: string) {
    this.lines.push(comment(text));
  }

  /** A custom block, verbatim; it may have moved the tool or changed modes. */
  custom(block: string) {
    this.lines.push(...block.replace(/\r\n?/g, "\n").replace(/\n$/, "").split("\n"));
    this.forget();
  }

  /** Writes every word again from now on, as if the tool's position were unknown. */
  forget() {
    this.written = {};
  }

  rapid(to: Axes) {
    this.rapidWork(this.toWork(to));
  }

  rapidWork(to: Axes) {
    this.move("G0", to);
  }

  feed(to: Axes, feedRate: number) {
    this.move("G1", this.toWork(to), feedRate);
  }

  toString(): string {
    return `${this.lines.join("\n")}\n`;
  }

  private toWork(to: Axes): Axes {
    const [x, y, z] = this.offset;
    return {
      ...(to.x !== undefined && { x: to.x + x }),
      ...(to.y !== undefined && { y: to.y + y }),
      ...(to.z !== undefined && { z: to.z + z }),
    };
  }

  private move(code: "G0" | "G1", to: Axes, feedRate?: number) {
    const words: string[] = [];
    for (const axis of AXES) {
      const value = to[axis];
      if (value === undefined) continue;
      const text = formatNumber(value);
      if (this.written[axis] === text) continue;
      this.written[axis] = text;
      words.push(`${axis.toUpperCase()}${text}`);
    }
    // Rounding can make a short move go nowhere.
    if (words.length === 0) return;
    if (feedRate !== undefined) {
      const text = formatNumber(feedRate);
      if (this.written.f !== text) {
        this.written.f = text;
        words.push(`F${text}`);
      }
    }
    this.lines.push([code, ...words].join(" "));
  }
}

/** Where the touch-off pad is, in work coordinates, and how wide. */
function padLabel(stock: Stock, { x, y, diameter }: TouchOff): string {
  const [ox, oy] = stockOffset(stock);
  return `X${formatNumber(x + ox)} Y${formatNumber(y + oy)}, ${formatNumber(diameter)} mm across`;
}

/** A G-code comment. GRBL comments can't nest or span lines. */
function comment(text: string): string {
  const safe = text
    .replace(/\(/g, "[")
    .replace(/\)/g, "]")
    // biome-ignore lint/suspicious/noControlCharactersInRegex: control characters are what it matches
    .replace(/[\u0000-\u001f\u007f]+/g, " ");
  return `(${safe})`;
}

/**
 * The fastest a feed from `from` to `to` may go: neither its XY nor its Z
 * component may exceed the machine's maximum.
 */
function limitFeed(from: Vec3, to: Vec3, feedRate: number, machine: Machine | null) {
  if (machine === null) return feedRate;
  const { maxFeedXY, maxFeedZ } = machine;
  const xy = Math.hypot(to[0] - from[0], to[1] - from[1]);
  const z = Math.abs(to[2] - from[2]);
  const length = Math.hypot(xy, z);
  let limit = feedRate;
  if (xy > 0) limit = Math.min(limit, (maxFeedXY * length) / xy);
  if (z > 0) limit = Math.min(limit, (maxFeedZ * length) / z);
  // Rounded down, so the written feed never exceeds the limit.
  return limit < feedRate ? Math.floor(limit * 1000) / 1000 : feedRate;
}

/** The `S` value for `rpm`, kept in the machine's range; `null` for a manual spindle. */
function spindleSpeed(rpm: number, machine: Machine | null) {
  if (machine === null) return { value: rpm, clamped: false };
  const { spindleRpmMin: min, spindleRpmMax: max } = machine;
  if (min === null || max === null) return { value: null, clamped: false };
  const value = Math.min(Math.max(rpm, min), max);
  return { value, clamped: value !== rpm };
}

/** Whether two tool snapshots are the same bit, so no tool change is needed. */
function sameBit(a: Tool, b: Tool): boolean {
  return (
    a.name === b.name &&
    a.type === b.type &&
    a.diameter === b.diameter &&
    a.fluteCount === b.fluteCount &&
    a.fluteLength === b.fluteLength &&
    a.cutDirection === b.cutDirection &&
    a.vAngle === b.vAngle &&
    a.tipDiameter === b.tipDiameter
  );
}

/**
 * The cutter shape the G-code simulation sweeps with (ADR-0042), in
 * millimetres and degrees, leaving out the fields that don't apply:
 * `(Furrow tool: type=v_bit diameter=12 vAngle=60 tipDiameter=0.2)`.
 */
export function toolShapeComment({ type, diameter, vAngle, tipDiameter }: Tool): string {
  const fields = [`type=${type}`, `diameter=${formatNumber(diameter)}`];
  if (vAngle !== null) fields.push(`vAngle=${formatNumber(vAngle)}`);
  if (tipDiameter !== null) fields.push(`tipDiameter=${formatNumber(tipDiameter)}`);
  return comment(`Furrow tool: ${fields.join(" ")}`);
}

function toolLabel(tool: Tool): string {
  return `${tool.name}, ${formatNumber(tool.diameter)} mm`;
}

const ANCHOR_LABELS = {
  bottom_left: "at the bottom-left corner",
  bottom_center: "at the middle of the bottom edge",
  bottom_right: "at the bottom-right corner",
  middle_left: "at the middle of the left edge",
  center: "at the centre",
  middle_right: "at the middle of the right edge",
  top_left: "at the top-left corner",
  top_center: "at the middle of the top edge",
  top_right: "at the top-right corner",
} as const satisfies Record<StockAnchor, string>;

function xyZeroLabel({ xyOrigin: origin }: Stock): string {
  if (origin.anchor !== "custom") return `${ANCHOR_LABELS[origin.anchor]} of the stock`;
  return (
    `at X${formatNumber(origin.x)} Y${formatNumber(origin.y)} mm ` +
    "from the stock's bottom-left corner"
  );
}

function zZeroLabel({ zOrigin }: Stock): string {
  return zOrigin === "stock_top" ? "at the stock top" : "at the machine bed";
}

function plural(count: number, noun: string): string {
  return `${count} ${noun}${count === 1 ? "" : "s"}`;
}
